def _split(pool, seed):
    """Deterministic 80/20 shuffle-then-slice split. Same seed always gives the
    same train/held partition, independent of the pool's original ordering."""
    shuffled = list(pool)
    random.Random(seed).shuffle(shuffled)
    cut = int(len(shuffled) * (1 - HELD_OUT_FRACTION))
    return shuffled[:cut], shuffled[cut:]


